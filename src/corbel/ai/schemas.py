"""Pydantic schemas for AI Gateway requests, responses, and token accounting."""

from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class ModelProviderType(str, Enum):
    """Supported model provider types."""

    MOCK = "mock"
    ANTHROPIC = "anthropic"
    OPENAI = "openai"


class TokenUsage(BaseModel):
    """Token consumption metrics for an AI model invocation."""

    prompt_tokens: int = Field(default=0, ge=0, description="Input prompt tokens consumed")
    completion_tokens: int = Field(default=0, ge=0, description="Completion tokens produced")
    total_tokens: int = Field(default=0, ge=0, description="Total tokens consumed")


class ModelRequest(BaseModel):
    """Provider-neutral model execution request."""

    system_prompt: str = Field(description="System instructions defining the model role and bounds")
    user_prompt: str = Field(description="User prompt or contextual task input")
    temperature: float = Field(default=0.0, ge=0.0, le=2.0, description="Sampling temperature")
    max_tokens: int = Field(default=2048, ge=1, le=8192, description="Maximum completion tokens")
    response_schema: dict[str, Any] | None = Field(
        default=None,
        description="Optional JSON Schema dict defining expected structured output",
    )


class ModelResponse(BaseModel):
    """Standardized response from an AI model provider."""

    provider: str = Field(description="Name of the model provider (e.g., 'mock', 'anthropic', 'openai')")
    model: str = Field(description="Model identifier (e.g., 'claude-3-5-sonnet', 'gpt-4o')")
    content: str = Field(description="Raw text content generated by the model")
    structured_data: dict[str, Any] | None = Field(
        default=None,
        description="Parsed and validated structured data dictionary if schema was requested",
    )
    token_usage: TokenUsage = Field(default_factory=TokenUsage, description="Token consumption metrics")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Total execution time in milliseconds")
