"""Pydantic v2 schemas for Phase 11: Use-Case Architect."""

import uuid
from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class ArchitectureAlternative(BaseModel):
    """An alternative technical approach considered and evaluated."""

    model_config = ConfigDict(extra="ignore")

    approach: str
    pros: list[str] = Field(default_factory=list)
    cons: list[str] = Field(default_factory=list)
    rejection_reason: str


class ArchitectureRationale(BaseModel):
    """Deep technical justification for the recommended solution pattern."""

    model_config = ConfigDict(extra="ignore")

    recommended_pattern: str
    justification: str
    deterministic_components: list[str] = Field(default_factory=list)
    retrieval_components: list[str] = Field(default_factory=list)
    agentic_components: list[str] = Field(default_factory=list)
    alternatives_considered: list[ArchitectureAlternative] = Field(default_factory=list)


class ImplementationMilestone(BaseModel):
    """A structured delivery milestone in the implementation plan."""

    model_config = ConfigDict(extra="ignore")

    milestone_id: str
    title: str
    description: str
    target_components: list[str] = Field(default_factory=list)
    dependencies: list[str] = Field(default_factory=list)
    estimated_effort: str
    acceptance_criteria: list[str] = Field(default_factory=list)


class TechnicalRisk(BaseModel):
    """An identified technical risk and its mitigation strategy."""

    model_config = ConfigDict(extra="ignore")

    risk: str
    severity: str  # LOW, MEDIUM, HIGH, CRITICAL
    mitigation: str


class InputsAndOutputs(BaseModel):
    """Structured operational I/O definition."""

    model_config = ConfigDict(extra="ignore")

    inputs: list[str] = Field(default_factory=list)
    outputs: list[str] = Field(default_factory=list)
    decisions: list[str] = Field(default_factory=list)
    actions: list[str] = Field(default_factory=list)


class EstimatesAndAssumptions(BaseModel):
    """Estimates and explicitly separated assumptions vs verified capabilities."""

    model_config = ConfigDict(extra="ignore")

    delivery_estimates: list[str] = Field(default_factory=list)
    verified_capabilities: list[str] = Field(default_factory=list)
    unverified_assumptions: list[str] = Field(default_factory=list)


class UseCaseSpecification(BaseModel):
    """Validated, versioned, structured solution specification generated by the Use-Case Architect.

    Conforms to all Phase 11 Section 3.5 requirements.
    """

    model_config = ConfigDict(extra="ignore")

    use_case_id: uuid.UUID
    version_number: int
    title: str
    description: str
    business_objective: str
    expected_outcomes: list[str] = Field(default_factory=list)
    stakeholders_and_roles: list[str] = Field(default_factory=list)
    workflow_description: str
    inputs_and_outputs: InputsAndOutputs
    source_systems: list[str] = Field(default_factory=list)
    data_classification: str = "INTERNAL"
    freshness_and_latency: str
    retrieval_requirements: str
    required_tools_and_actions: list[str] = Field(default_factory=list)
    risk_level: str = "MEDIUM"  # LOW, MEDIUM, HIGH, CRITICAL
    human_approval_requirements: list[str] = Field(default_factory=list)
    proposed_architecture: str
    architecture_rationale_and_alternatives: ArchitectureRationale
    implementation_plan: list[ImplementationMilestone] = Field(default_factory=list)
    estimates_and_assumptions: EstimatesAndAssumptions
    risks_and_dependencies: list[TechnicalRisk] = Field(default_factory=list)
    open_questions: list[str] = Field(default_factory=list)
    success_metrics: list[str] = Field(default_factory=list)
    evaluation_plan: str
    specification_status: str = "REVIEW"
    created_at: datetime
    updated_at: datetime


class ExtractedRequirements(BaseModel):
    """Structured extraction of user requirements and discovery state."""

    model_config = ConfigDict(extra="ignore")

    business_objective: str | None = None
    expected_outcomes: list[str] = Field(default_factory=list)
    stakeholders: list[str] = Field(default_factory=list)
    workflows: list[str] = Field(default_factory=list)
    inputs: list[str] = Field(default_factory=list)
    outputs: list[str] = Field(default_factory=list)
    source_systems: list[str] = Field(default_factory=list)
    data_sensitivity: str | None = None
    freshness_latency: str | None = None
    confirmed_requirements: list[str] = Field(default_factory=list)
    unverified_assumptions: list[str] = Field(default_factory=list)


class DiscoveryMessageItem(BaseModel):
    """A single discovery message item."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    sender_role: str
    message_text: str
    extracted_requirements: ExtractedRequirements | None = None
    clarification_questions: list[str] | None = None
    created_at: datetime


class DiscoveryTurnResponse(BaseModel):
    """Response returned after processing a discovery turn."""

    model_config = ConfigDict(from_attributes=True)

    user_message: DiscoveryMessageItem
    assistant_message: DiscoveryMessageItem
    can_generate_specification: bool


class UseCaseCreateRequest(BaseModel):
    """Request payload to create a new Use Case."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(..., min_length=3, max_length=255)
    description: str = Field(..., min_length=10)


class UseCaseUpdateRequest(BaseModel):
    """Request payload to update use case metadata."""

    model_config = ConfigDict(extra="forbid")

    title: str | None = Field(None, min_length=3, max_length=255)
    description: str | None = Field(None, min_length=10)


class UseCaseMessageCreateRequest(BaseModel):
    """Request payload to post a discovery response."""

    model_config = ConfigDict(extra="forbid")

    message_text: str = Field(..., min_length=1)


class UseCaseResponse(BaseModel):
    """Summary response for a Use Case."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    organization_id: uuid.UUID
    project_id: uuid.UUID
    title: str
    description: str
    status: str
    current_version: int
    created_by: uuid.UUID
    approved_by: uuid.UUID | None = None
    approved_at: datetime | None = None
    created_at: datetime
    updated_at: datetime


class UseCaseDetailResponse(UseCaseResponse):
    """Detailed response for a Use Case including messages and latest specification."""

    messages: list[DiscoveryMessageItem] = Field(default_factory=list)
    latest_specification: UseCaseSpecification | None = None


class SpecificationVersionSummary(BaseModel):
    """Summary of a saved specification version."""

    model_config = ConfigDict(from_attributes=True)

    version: int
    created_by: uuid.UUID
    created_at: datetime
    title: str
    proposed_architecture: str
    risk_level: str


class SpecificationDiffResponse(BaseModel):
    """Structural diff between two specification revisions."""

    model_config = ConfigDict(extra="ignore")

    use_case_id: uuid.UUID
    v1: int
    v2: int
    differences: dict[str, dict[str, Any]]
    summary: str
